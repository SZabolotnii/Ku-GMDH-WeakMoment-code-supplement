pick <- function(tab, key_col, key, comparison, unit = NULL) {
  r <- tab[tab[[key_col]] == key & tab$comparison == comparison, , drop = FALSE]
  if (!is.null(unit)) r <- r[r$unit == unit, , drop = FALSE]
  if (nrow(r) != 1L) stop("inference row not unique: ", key, " / ", comparison, " / ", unit)
  r
}
fmt_num <- function(x) gsub("-", "$-$", sprintf("%+.1f", as.numeric(x)), fixed = TRUE)
inf_row <- function(label, unit_label, r, n_col, win_col, p_col) {
  paste(label, unit_label,
        sprintf("%d/%d", as.integer(r[[win_col]]), as.integer(r[[n_col]])),
        fmt_num(r$median_delta_pct %||% r$median_unit_delta_pct),
        sprintf("[%s, %s]", fmt_num(r$bootstrap_ci_lo_pct), fmt_num(r$bootstrap_ci_hi_pct)),
        sprintf("%.3f", as.numeric(r[[p_col]])),
        sep = " & ")
}
`%||%` <- function(a, b) if (is.null(a) || !length(a)) b else a
