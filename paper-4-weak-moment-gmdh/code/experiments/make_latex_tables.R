  "\\end{tabular}",
  "\\end{table}"
)
writeLines(claim_tex, file.path(tables_dir, "table_final_claim_rows.tex"))

dispatch_table <- read_csv(file.path(results_dir, "dispatch_retune.csv"))
selector_label <- c(
  islr_credit_balance = "credit balance",
  sru_y2_static = "SRU \\(y_2\\)",
  gas_turbine_nox_2015_raw = "gas-turbine NOx"
)
selector_note <- c(
  islr_credit_balance = "old cumulant-gate +10.0\\,\\%",
  sru_y2_static = "single-split valgate lost; run not retained",
  gas_turbine_nox_2015_raw = "tie; hardest, near-Gaussian skew"
)
dispatch_rows <- apply(dispatch_table, 1, function(row) {
  row <- trimws(row)
  dataset <- row[["dataset"]]
  result <- sprintf(
    "%s (%s)",
    fmt_delta(row[["autovalgate_vs_rob"]], function(v) v < -0.5),
    selector_note[[dataset]]
  )
  paste(
    selector_label[[dataset]],
    latex_escape(row[["proto"]]),
    result,
    sep = " & "
  )
})

dispatch_tex <- c(
  "% Generated by code/experiments/make_latex_tables.R from results/dispatch_retune.csv.",
  "\\begin{table}[H]",
  "\\centering",
