    latex_escape(row[["best_weak_method"]]),
    fmt_delta(row[["weak_vs_robust_stat_trmse_pct"]], function(v) v <= BOLD_ROBUST_PCT),
    fmt_delta(row[["weak_vs_tree_trmse_pct"]], function(v) v <= BOLD_TREE_PCT),
    latex_escape(verdict_for(dataset, row[["claim_reading"]])),
    sep = " & "
  )
})

