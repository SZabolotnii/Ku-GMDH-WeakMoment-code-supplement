  "\\midrule",
  paste0(dispatch_rows, " \\\\"),
  "\\bottomrule",
  "\\end{tabular}",
  "\\end{table}"
)
writeLines(dispatch_tex, file.path(tables_dir, "table_validation_gate_selector.tex"))

manifest <- data.frame(
  table = c("table_final_claim_rows.tex", "table_validation_gate_selector.tex"),
