latex_escape <- function(x) {
  x <- as.character(x)
  x <- gsub("\\\\", "\\\\textbackslash{}", x)
  x <- gsub("([#$%&_{}])", "\\\\\\1", x, perl = TRUE)
  x <- gsub("~", "\\\\textasciitilde{}", x, fixed = TRUE)
  x <- gsub("\\^", "\\\\textasciicircum{}", x)
  x
}

fmt_pct <- function(x) {
  sprintf("%+.1f\\,\\%%", as.numeric(x))
}

fmt_delta <- function(x, bold_if = function(v) FALSE) {
  v <- as.numeric(x)
  out <- fmt_pct(v)
  if (isTRUE(bold_if(v))) {
    out <- paste0("\\textbf{", out, "}")
  }
  out
}

