verdict_for <- function(dataset, claim) {
  overrides <- c(
    sru_y1_dynamic = "robust-stat + tree positive",
    islr_credit_balance = "modest robust-stat only",
    insurance_autobi_loss = "robust-stat + tree positive",
    fremtpl2_severity_raw = "heavy-tail rescue / tree positive",
    sru_y2_static = "robust-stat tie / tree positive",
    concrete = "negative control"
  )
  if (dataset %in% names(overrides)) return(overrides[[dataset]])
  claim_label[[claim]]
}

num_word <- function(k) {
  w <- c("none", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten")
  if (k >= 0 && k <= 10) w[[k + 1]] else as.character(k)
}

