#!/usr/bin/env Rscript

script_path <- commandArgs(trailingOnly = FALSE)
file_arg <- grep("^--file=", script_path, value = TRUE)
if (length(file_arg) == 0) {
  stop("Cannot determine script path from commandArgs(). Run this script via Rscript.")
}
script_file <- normalizePath(sub("^--file=", "", file_arg[[1]]), mustWork = TRUE)
root <- normalizePath(file.path(dirname(script_file), "../../.."), mustWork = TRUE)
p4_dir <- file.path(root, "paper-4-weak-moment-gmdh")
results_dir <- file.path(p4_dir, "results")
tables_dir <- file.path(p4_dir, "latex", "tables")
dir.create(tables_dir, recursive = TRUE, showWarnings = FALSE)

latex_escape <- function(x) {
  x <- as.character(x)
  x <- gsub("\\\\", "\\\\textbackslash{}", x)
  x <- gsub("([#$%&_{}])", "\\\\\\1", x, perl = TRUE)
  x <- gsub("~", "\\\\textasciitilde{}", x, fixed = TRUE)
  x <- gsub("\\^", "\\\\textasciicircum{}", x)
  x
}

fmt_pct <- function(x) {
  sprintf("%+.1f\\,\\%%", as.numeric(x))
}

fmt_delta <- function(x, bold_if = function(v) FALSE) {
  v <- as.numeric(x)
  out <- fmt_pct(v)
  if (isTRUE(bold_if(v))) {
    out <- paste0("\\textbf{", out, "}")
  }
  out
}

domain_label <- c(
  soft_sensor = "Soft-sensor",
  emissions = "Emissions",
  finance = "Finance",
  insurance = "Insurance",
  cross_section_control = "Cross-sec"
)

dataset_label <- c(
  sru_y1_dynamic = "\\textbf{SRU \\(y_1\\) dynamic}",
  gas_turbine_co_2015_raw = "\\textbf{gas-turbine CO}",
  gas_turbine_nox_2015_raw = "\\textbf{gas-turbine NOx}",
  islr_credit_balance = "\\textbf{credit balance}",
  insurance_autobi_loss = "\\textbf{AutoBi loss}",
  fremtpl2_severity_raw = "\\textbf{freMTPL2 raw severity}",
  sru_y2_static = "SRU \\(y_2\\) static",
  concrete = "concrete"
)

claim_label <- c(
  positive_vs_robust_stat_and_tree = "positive vs robust-stat and tree",
  positive_vs_robust_stat_only = "robust-stat positive, tree loses claim",
  tree_positive_control_or_rescue = "robust-stat tie, tree positive",
  negative_or_loss_control = "negative control"
)

verdict_for <- function(dataset, claim) {
  overrides <- c(
    sru_y1_dynamic = "robust-stat + tree positive",
    islr_credit_balance = "modest robust-stat only",
    insurance_autobi_loss = "robust-stat + tree positive",
    fremtpl2_severity_raw = "heavy-tail rescue / tree positive",
    sru_y2_static = "robust-stat tie / tree positive",
    concrete = "negative control"
  )
  if (dataset %in% names(overrides)) return(overrides[[dataset]])
  claim_label[[claim]]
}

read_csv <- function(path) {
  read.csv(path, stringsAsFactors = FALSE, check.names = FALSE)
}

claim_table <- read_csv(file.path(results_dir, "final_claim_evidence_table.csv"))
claim_rows <- apply(claim_table, 1, function(row) {
  row <- trimws(row)
  dataset <- row[["dataset"]]
  domain <- row[["domain"]]
  left <- sprintf(
    "%s: %s (%s)",
    domain_label[[domain]],
    dataset_label[[dataset]],
    row[["n"]]
  )
  paste(
    left,
    latex_escape(row[["protocol"]]),
    latex_escape(row[["best_weak_method"]]),
    fmt_delta(row[["weak_vs_robust_stat_trmse_pct"]], function(v) v <= -3),
    fmt_delta(row[["weak_vs_tree_trmse_pct"]], function(v) v <= -10),
    latex_escape(verdict_for(dataset, row[["claim_reading"]])),
    sep = " & "
  )
})

